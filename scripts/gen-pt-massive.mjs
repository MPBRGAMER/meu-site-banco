// Generate dictionary
const dict = { ...MANUAL };
let autoCount = 0;
for (const word of WORDS) {
  const r = auto(word);
  if (r) {
    const [key, val] = r;
    // Skip single-letter keys (false positives)
    if (key.length <= 1) continue;
    // Skip identity pairs
    if (key === val) continue;
    // Don't override MANUAL entries
    if (!dict[key]) {
      dict[key] = val;
      autoCount++;
    }
  }
}

const total = Object.keys(dict).length;
console.log(`PT dictionary: ${total} entries (${Object.keys(MANUAL).length} manual + ${autoCount} auto-generated)`);
console.log('\nSample tests:');
const tests = ['voce eh legal','nao sei pq','tbm blz flw','ola boa tarde que horas sao por ai','q eh isso','oi cara tudo bem','e ai mano','Voce EH LEGAL','novo nivel alcancado'];
for (const t of tests) {
  let r = t;
  for (const [k,v] of Object.entries(dict)) {
    r = r.replace(new RegExp('\\b'+k.replace(/[.*+?^${}()|[\\]\\]/g,'\\$&')+'\\b','gi'), (m) => {
      const fix = dict[k];
      if (!fix) return m;
      if (m[0] === m[0].toUpperCase() && fix[0]) return fix[0].toUpperCase() + fix.slice(1);
      return fix;
    });
  }
  const icon = t === r ? '  ' : '✅';
  console.log(icon, JSON.stringify(t), '=>', JSON.stringify(r));
}

